#!/usr/bin/env bash
# S0.4 Verify: contracts/internal.yaml is valid OpenAPI with valid examples,
# matches internal/store and ring.yaml (contracts/contracts_test.go), the
# shared outcome table in contracts/README.md covers every store outcome, and
# `make gen` leaves no diff.
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

GEN_DIR="internal/internalapi"
GEN_FILE="$GEN_DIR/types.gen.go"
FAILED=0

ok()   { printf 'ok    %s\n' "$1"; }
fail() { printf 'FAIL  %s\n' "$1"; FAILED=$((FAILED + 1)); }

for f in contracts/internal.yaml contracts/README.md; do
	if [ -f "$f" ]; then ok "$f exists"; else fail "$f missing"; fi
done

# Spec lint, examples, §40 routes, store parity, ring parity, outcome table.
if go test -count=1 -v ./contracts; then
	ok "contract tests (lint, examples, routes, store parity, outcome table)"
else
	fail "contract tests"
fi

# Clean means the checked-in generated code is exactly what make gen writes.
snapshot() { find "$GEN_DIR" -type f -exec sha256sum {} + 2>/dev/null | sort; }
before="$(snapshot)"
if make -s gen; then ok "make gen"; else fail "make gen"; fi

if [ -f "$GEN_FILE" ] && grep -q 'oapi-codegen' "$GEN_FILE"; then
	ok "$GEN_FILE generated from contracts/internal.yaml"
else
	fail "$GEN_FILE missing or not generated by oapi-codegen"
fi

if [ "$before" = "$(snapshot)" ]; then
	ok "make gen leaves no diff"
else
	diff <(printf '%s\n' "$before") <(snapshot)
	fail "make gen changed $GEN_DIR (regenerate and commit)"
fi

if go build ./...; then ok "go build ./..."; else fail "go build ./..."; fi

if go mod tidy -diff >/dev/null; then ok "go.mod tidy"; else fail "go.mod needs go mod tidy"; fi

if [ "$FAILED" -eq 0 ]; then
	echo "verify-S0.4: all checks passed"
else
	echo "verify-S0.4: $FAILED check(s) failed"
	exit 1
fi
